/** Blocks a right click uses (opens, toggles, edits) instead of placing a block against them, unless the bot sneaks. */
const EXACT = new Set([
  'chest',
  'trapped_chest',
  'ender_chest',
  'barrel',
  'crafting_table',
  'furnace',
  'blast_furnace',
  'smoker',
  'anvil',
  'chipped_anvil',
  'damaged_anvil',
  'enchanting_table',
  'brewing_stand',
  'hopper',
  'dispenser',
  'dropper',
  'loom',
  'stonecutter',
  'grindstone',
  'smithing_table',
  'cartography_table',
  'fletching_table',
  'lectern',
  'lever',
  'note_block',
  'jukebox',
  'bell',
  'beacon',
  'cake',
  'comparator',
  'repeater',
  'daylight_detector',
  'composter',
  'cauldron',
  'respawn_anchor',
])
const SUFFIXES = [
  '_door',
  '_trapdoor',
  '_fence_gate',
  '_button',
  '_bed',
  '_sign',
  '_hanging_sign',
  '_shulker_box',
]

export const isUsedByClick = (name: string): boolean =>
  EXACT.has(name) || SUFFIXES.some((suffix) => name.endsWith(suffix)) || name === 'shulker_box'
